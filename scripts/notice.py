# ruff: noqa: E501  (HB-196: rendered prose and paths are one line each)
"""HB-196 Part C item 11: NOTICE, the licences and notices for everything hazbrief ships, generated from the held
records, never typed.

Each part is read from the file that holds it:

- hazbrief's own licence and the template's (`LICENSE`, `LICENSE-TEMPLATE`), named with their first line;
- the code vendored into every brief page: Leaflet (`src/hazbrief/brief/vendor/leaflet-1.9.4/LICENSE`, verbatim);
- the FGDC Homeland Security Working Group symbols the map draws: their `corpus/sources.yaml` row's notes, which
  quote what every font's name table states;
- the engines the optional models image builds locally and does not distribute: SLAB (its `corpus/sources.yaml` row's
  notes quote `SLAB.FOR`'s own terms) and SCICHEM (`deploy/models/scichem/NOTICE`, verbatim, as the image installs
  it under `/licenses/SCICHEM`);
- every public source the server and the brief read: each row of the source catalog (`docs/sources/catalog.yaml`)
  with its `terms`, which cite the held page, and the notices the server serves as its `attribution` resource
  (`docs/stylebook/ATTRIBUTION.md`, verbatim).

    uv run python scripts/notice.py            # write NOTICE
    uv run python scripts/notice.py --check    # write nothing; exit 1 when NOTICE differs from its sources

The script fails, writing nothing, when a named file or a named `corpus/sources.yaml` row is missing.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "NOTICE"
SOURCES = ROOT / "corpus" / "sources.yaml"
CATALOG = ROOT / "docs" / "sources" / "catalog.yaml"
ATTRIBUTION = ROOT / "docs" / "stylebook" / "ATTRIBUTION.md"
LEAFLET = ROOT / "src" / "hazbrief" / "brief" / "vendor" / "leaflet-1.9.4" / "LICENSE"
SCICHEM_NOTICE = ROOT / "deploy" / "models" / "scichem" / "NOTICE"
#: the corpus rows whose notes hold a shipped component's terms
FGDC_FONTS = "fgdc-hswg-ers-fonts-v2-20"
SLAB_CODE = "epa-slab-code"
RULE = "=" * 100


class NoticeError(Exception):
    """A file or a held record NOTICE cannot be generated without."""


def read(p: Path) -> str:
    if not p.is_file():
        raise NoticeError(f"{p.relative_to(ROOT)} is missing")
    return p.read_text(encoding="utf-8").rstrip("\n")


def source_row(doc_id: str) -> dict:
    rows = yaml.safe_load(read(SOURCES))
    rows = rows.get("sources", rows) if isinstance(rows, dict) else rows
    hits = [r for r in rows if isinstance(r, dict) and r.get("doc_id") == doc_id]
    if len(hits) != 1:
        raise NoticeError(f"corpus/sources.yaml: {len(hits)} rows for {doc_id}, not 1")
    return hits[0]


def _one(text: str) -> str:
    return " ".join(str(text).split())


def part(title: str, origin: str, body: str) -> list[str]:
    return [RULE, title, f"From: {origin}", RULE, "", body, ""]


def render() -> str:
    out = [
        "NOTICE for hazbrief-mcp",
        "",
        "Generated by scripts/notice.py from the files and held records each part names; do not edit.",
        "The licences and notices of everything this repository ships or builds: its own code, the code",
        "vendored into each brief page, the map symbols, the engines of the optional models image, and the",
        "terms of every public source the server and the brief read.",
        "",
    ]
    lic = read(ROOT / "LICENSE").splitlines()
    tmpl = read(ROOT / "LICENSE-TEMPLATE").splitlines()
    out += part(
        "1. hazbrief-mcp and the template it was adapted from",
        "LICENSE; LICENSE-TEMPLATE",
        f"hazbrief-mcp: {lic[0]}; the full text is LICENSE.\n"
        f"GSA-TTS/mcp-hackathon-template, the server skeleton's origin (README, Origin): {tmpl[0]}; "
        "the full text is LICENSE-TEMPLATE.",
    )
    out += part(
        "2. Leaflet 1.9.4, vendored into every brief page",
        str(LEAFLET.relative_to(ROOT)),
        read(LEAFLET),
    )
    fonts = source_row(FGDC_FONTS)
    out += part(
        "3. The FGDC Homeland Security Working Group emergency response symbols the map draws",
        f"corpus/sources.yaml {FGDC_FONTS} ({fonts.get('source_page')})",
        f"{fonts.get('title')}, {fonts.get('publisher')}, edition {fonts.get('edition')}.\n"
        + _one(fonts.get("notes")),
    )
    slab = source_row(SLAB_CODE)
    out += part(
        "4. SLAB, built in the optional models image (never in the server image; not distributed as a binary)",
        f"corpus/sources.yaml {SLAB_CODE} ({slab.get('url')})",
        f"{slab.get('title')}, {slab.get('publisher')}, {slab.get('edition')}. Reuse: {slab.get('reuse')}.\n"
        + _one(slab.get("notes"))
        + "\nThe models image installs SLAB.FOR's own lines 1 to 20, which carry these terms, as /licenses/SLAB "
        "(deploy/models/Dockerfile).",
    )
    out += part(
        "5. SCICHEM, built in the optional models image (never in the server image; not distributed as a binary)",
        f"{SCICHEM_NOTICE.relative_to(ROOT)}, which the image installs as /licenses/SCICHEM",
        read(SCICHEM_NOTICE),
    )
    cat = yaml.safe_load(read(CATALOG))
    rows = cat.get("sources") if isinstance(cat, dict) else cat
    if not rows:
        raise NoticeError(f"{CATALOG.relative_to(ROOT)} holds no source rows")
    lines = []
    for r in rows:
        if not r.get("terms"):
            raise NoticeError(f"catalog row {r.get('id')} states no terms")
        lines.append(
            f"- {r['id']}: {_one(r.get('name', ''))}\n  Terms: {_one(r['terms'])}"
        )
    out += part(
        "6. Every public source the server and the brief read, with its terms as the held page states them",
        f"{CATALOG.relative_to(ROOT)} (each row's `terms` names the held document it quotes)",
        "\n".join(lines),
    )
    out += part(
        "7. The notices the server serves as its attribution resource",
        str(ATTRIBUTION.relative_to(ROOT)),
        read(ATTRIBUTION),
    )
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv: list[str]) -> int:
    try:
        text = render()
    except NoticeError as e:
        print(f"FATAL: {e}", file=sys.stderr)
        return 2
    if "--check" in argv:
        same = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print(
            "NOTICE equals its sources"
            if same
            else "NOTICE differs from its sources; run scripts/notice.py"
        )
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
