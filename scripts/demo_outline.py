#!/usr/bin/env python3
# ruff: noqa: E501  (the preflight's lines are prose strings, kept whole to read as printed)
"""HB-197 Part B, restated by HB-209 Part B: the demo's one-page outline, its paste-ready lines
and its preflight, from their data file.

    uv run python scripts/demo_outline.py           # writes OUTLINE.md, LINES.md and PREFLIGHT.md
    uv run python scripts/demo_outline.py --check   # exit 1 if any differs from a render

`docs/submission/demo/outline.yaml` is the one source. OUTLINE.md is cues only: one level of
bullets under at most seven group headings, each bullet a point to make or a thing to show (the
page, the control and the cue), then the measured waits, each read from its run record.
LINES.md is the start line and the typed demo lines, each read from the held record that says
it worked. PREFLIGHT.md is the checks before recording, each a command and what it prints, and
what to do when a live cloud is refused; its numbers are read here from the committed files
`outline.yaml` names and from `scripts/check_video.sh --budget`, never typed.
`test_hb197_demo.py` holds the limits.
"""

from __future__ import annotations

import argparse
import csv
import re
import subprocess
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
DATA = REPO / "docs" / "submission" / "demo" / "outline.yaml"
OUTLINE = REPO / "docs" / "submission" / "demo" / "OUTLINE.md"
LINES = REPO / "docs" / "submission" / "demo" / "LINES.md"
PREFLIGHT = REPO / "docs" / "submission" / "demo" / "PREFLIGHT.md"
CHECK_VIDEO = REPO / "scripts" / "check_video.sh"
GENERATED = "<!-- Generated by scripts/demo_outline.py from docs/submission/demo/outline.yaml (HB-197, HB-209); do not edit. -->"

#: where a `show` cue's page is, as printed: the live page is the brief itself
PAGE_LABEL = {"live": "", "timeline.html": " Timeline page", "tevv.html": " TEVV page"}


def load() -> dict:
    return yaml.safe_load(DATA.read_text(encoding="utf-8"))


def cue_text(cue: dict) -> str:
    """One bullet's text, without the list marker."""
    if "point" in cue:
        return f"**Point:** {cue['point']}"
    s = cue["show"]
    where = "start page" if s["page"] == "start" else s["brief"] + PAGE_LABEL[s["page"]]
    return f"**Show** {where}, **{s['control']}**: {cue['cue']}"


def words(text: str) -> int:
    return len(text.replace("**", "").split())


def run_row(path: str, run: str) -> dict:
    """One run's row of a live runs.tsv (HB-207's or HB-208's)."""
    with (REPO / path).open(encoding="utf-8") as fh:
        for row in csv.DictReader(fh, delimiter="\t"):
            if row["run"] == run:
                return row
    raise LookupError(f"{path} has no run {run}")


def _seconds(v: str) -> str | None:
    try:
        return f"{float(v):.1f} s"
    except (TypeError, ValueError):
        return None


def wait_text(w: dict) -> str:
    row = run_row(w["file"], w["run"])
    first = _seconds(row.get("first_frame_s", ""))
    last = _seconds(row.get("last_section_s", ""))
    if last is None:
        raise ValueError(f"{w['file']} {w['run']}: no last_section_s")
    parts = (
        [f"first frame {first}"] if first and row.get("mode") != "recorded" else []
    ) + [f"last section {last}"]
    return f"{w['label']}: {', '.join(parts)}"


def render_outline(data: dict) -> str:
    o = data["outline"]
    lines = [GENERATED, f"# {o['title']}", "", o["intro"], ""]
    n = 0
    for n, g in enumerate(o["groups"], 1):
        lines.append(f"## {n}. {g['title']}")
        lines.append("")
        lines += [f"- {cue_text(c)}" for c in g["cues"]]
        lines.append("")
    w = o["waits"]
    lines.append(f"## {n + 1}. {w['title']}")
    lines.append("")
    lines += [f"- {wait_text(r)}" for r in w["runs"]]
    lines.append("")
    return "\n".join(lines)


def typed_lines(data: dict) -> list[tuple[str, str]]:
    """(line, point) for each typed line, read from the held record that says it worked; a line
    that record does not print, or that the runs file shows no run of, is refused."""
    t = data["lines"]["typed"]
    text = (REPO / t["from"]).read_text(encoding="utf-8")
    with (REPO / t["runs"]).open(encoding="utf-8") as fh:
        ran = {r["line"]: r["point"] for r in csv.DictReader(fh, delimiter="\t")}
    out = []
    for line in t["lines"]:
        m = re.search(r"`" + re.escape(line) + r"` at (-?\d+\.\d+), (-?\d+\.\d+)", text)
        if not m:
            raise LookupError(f"{t['from']} does not print `{line}` at a point")
        point = f"{m.group(1)}, {m.group(2)}"
        if ran.get(line) != point:
            raise LookupError(f"{t['runs']} has no run of `{line}` at {point}")
        out.append((line, point))
    return out


def render_lines(data: dict) -> str:
    li = data["lines"]
    s = li["start"]
    held = " ".join((REPO / s["from"]).read_text(encoding="utf-8").split())
    for want in (s["command"], s["prints"]):
        if want not in held:
            raise LookupError(f"{s['from']} does not print {want!r}")
    lines = [
        GENERATED,
        f"# {li['title']}",
        "",
        f"Start the brief application (`{s['from']}`, step 1); it prints `{s['prints']}`:",
        "",
        "```bash",
        s["command"],
        "```",
        "",
        f"Each line below worked live as typed on the start page's entry form (`{li['typed']['from']}`): "
        "paste it there and click its point on the map. In Claude Desktop, give the point with the line.",
        "",
    ]
    for n, (line, point) in enumerate(typed_lines(data), 1):
        lines += [f"{n}. Point {point}:", "", "   ```text", f"   {line}", "   ```", ""]
    return "\n".join(lines)


def _tsv_row(path: str, brief: str) -> dict:
    with (REPO / path).open(encoding="utf-8") as fh:
        for row in csv.DictReader(fh, delimiter="\t"):
            if row["brief"] == brief:
                return row
    raise LookupError(f"{path} has no row for {brief}")


def budget_line(minutes: int) -> str:
    done = subprocess.run(
        ["bash", str(CHECK_VIDEO), "--budget", str(minutes)],
        capture_output=True,
        text=True,
        check=True,
    )
    return done.stdout.strip()


def render_preflight(data: dict) -> str:
    p = data["preflight"]
    load_s = float(_tsv_row(p["live_load"], p["brief"])["live_load_s"])
    # HB-213 item 7: no --no-google; with GOOGLE_MAPS_API_KEY set the served page draws Google's basemap and the
    # Traffic switch (HB-210, HB-211), without it Leaflet's
    serve = (
        f"uv run hazbrief brief docs/briefs/{p['brief']}/scenario.json --serve --replay "
        f"--now {p['now']}"
    )
    fallback = ", ".join(f"`{f}`" for f in p["fallback"])
    # each line opens with the same "50 MB is 400 megabits; ", printed once
    lines_b = [budget_line(m) for m in p["lengths_min"]]
    budgets = "; ".join([lines_b[0]] + [b.split("; ", 1)[-1] for b in lines_b[1:]])
    reencode = " ".join(p["reencode"].split())
    lines = [GENERATED, f"# {p['title']}", ""]
    n = 0
    for n, c in enumerate(p["checks"], 1):
        lines.append(f"{n}. {c['what']}: `{c['command']}` prints {c['expect']}.")
    rest = [
        # HB-221 item 6: items 7 and 8 each end with the line that rain no longer stops the cloud
        f"If a live cloud is refused: {' '.join(p['calm'].split())} {' '.join(p['rain'].split())}",
        f"{' '.join(p['domain_edge'].split())} {' '.join(p['rain'].split())}",
        f"A recorded brief by replay (no engine, no model call): `{serve}`; it serves {p['url']} and "
        f"loaded in {load_s:.1f} s in HB-192 (`{p['live_load']}`). With `GOOGLE_MAPS_API_KEY` set the page draws "
        "Google's basemap and its Traffic switch at 127.0.0.1 (Google refuses the key at localhost); without the key "
        "it draws Leaflet's.",
        f"Window: a {p['viewport']} viewport, the size of the deck's screenshots. Keep the EXERCISE banner, "
        "top and bottom, in frame.",
        f"If a page does not load: {fallback}.",
        f"The container: README's three lines serve the seven tools; its build needs the network (`{p['container']}`).",
        f"Size: {budgets}. Check the export with `scripts/check_video.sh demo.mp4` (exit 1 over the limit).",
        f"Over the limit: re-encode to H.264, `{reencode}`.",
    ]
    lines += [f"{n + i}. {t}" for i, t in enumerate(rest, 1)]
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare, write nothing")
    args = ap.parse_args(argv)
    data = load()
    want = {
        OUTLINE: render_outline(data),
        LINES: render_lines(data),
        PREFLIGHT: render_preflight(data),
    }
    if args.check:
        stale = [
            p.name
            for p, text in want.items()
            if not p.exists() or p.read_text(encoding="utf-8") != text
        ]
        if stale:
            print(
                f"stale: {', '.join(stale)}; run scripts/demo_outline.py",
                file=sys.stderr,
            )
            return 1
        print("OUTLINE.md, LINES.md and PREFLIGHT.md equal a fresh render")
        return 0
    for path, text in want.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
